'use client';
import type {CampusSnapshot} from '../contracts';
import type {CampusAdminSnapshot} from '../admin-metrics';
import {LearnerDashboard,AdminDashboard} from '../ui/dashboard';
import {JournalPanel} from '../ui/workspace';
import {DemoAi} from '../ui/demo-ai';
import {BusinessPanel,type BusinessView} from '../business/panel';
import {CommunityPanel} from '../community/panel';
import {SupportPanel} from '../support/panel';
import {SupportAdminPanel} from '../support/admin-panel';
import {SpaceAdminPanel} from '../space/admin-panel';
import {SpaceHttpMetrics} from '../space/http-metrics-panel';
import {BusinessCasesAdminPanel} from '../business/case-panel';
import {CommunityModerationPanel} from '../community/moderation-panel';
import {PersonalArchive} from '../business/archive-panel';
import {WebinarAdmin} from '../webinar/admin';
import {SpacePanel} from '../space/panel';
import {OfficePanel} from '../office/panel';
import {useMemo} from 'react';
export {SpacePanel};
export default function FeaturePanel({id,snapshot,adminSnapshot,onOpen,onAsk,onNavigate,handoff,onNotice,active=true}:{active?:boolean;id:string;snapshot:CampusSnapshot;adminSnapshot?:CampusAdminSnapshot;onOpen:(id:string)=>void;onAsk:(value:{lessonId:string;context:string})=>void;onNavigate:(id:string)=>void;handoff?:{lessonId:string;context:string}|null;onNotice:(text:string)=>void}){
 const cohort=snapshot.scopes.find(s=>s.enrollmentId===snapshot.selectedEnrollmentId)?.cohortId||'';
 const demoCohorts=useMemo(()=>snapshot.scopes.map(s=>({id:s.cohortId,name:s.cohortName,course_id:s.courseId,courses:{title:s.courseTitle,slug:'moonshot-demo'}})),[snapshot.scopes]);
 if(id==='growth')return <LearnerDashboard snapshot={snapshot} demo onOpen={onOpen} onRefresh={()=>onNotice('가상 학습 기록입니다. 실제 진행률은 DEV에서 확인합니다.')} onSelect={()=>onNotice('이 미리보기는 예시 기수 한 곳을 사용합니다.')}/>;
 if(id==='office')return <OfficePanel snapshot={snapshot} demo active={active}/>;
 if(id==='ai')return <DemoAi snapshot={snapshot} handoff={handoff} active={active}/>;
 if(id==='journal')return <JournalPanel snapshot={snapshot} demo active/>;
 if(id==='feedback'||id.startsWith('community:'))return <CommunityPanel snapshot={snapshot} demo onOpen={onOpen} initialTab={id==='feedback'?'feedback':id.split(':')[1] as 'mine'|'talent'|'demo_day'}/>;
 if(id.startsWith('business:'))return <BusinessPanel snapshot={snapshot} demo view={id.slice(9) as BusinessView} onOpenLesson={onOpen} onAsk={onAsk}/>;
 if(id.startsWith('support:'))return <SupportPanel snapshot={snapshot} demo initialTab={id.slice(8)} focused onOpen={onOpen} onAsk={onAsk}/>;
 if(id==='archive')return <PersonalArchive demo/>;
 if(id==='legacy-space')return <SpacePanel snapshot={snapshot} demo initialRenderer="classic" onNavigate={onNavigate} onOpenLesson={onOpen}/>;
 if(id==='admin:dashboard')return adminSnapshot?<AdminDashboard snapshot={adminSnapshot} onRefresh={()=>onNotice('가상 기수 현황입니다.')}/>:<p>기수 현황 예시가 준비되지 않았습니다.</p>;
 if(id==='admin:support')return <SupportAdminPanel cohortId={cohort} demo/>;
 if(id==='admin:space')return <><SpaceAdminPanel cohortId={cohort} demo/><SpaceHttpMetrics cohortId={cohort} demo/></>;
 if(id==='admin:cases')return <BusinessCasesAdminPanel cohortId={cohort} demo/>;
 if(id==='admin:moderation')return <CommunityModerationPanel cohortId={cohort} demo/>;
 if(id==='admin:links')return <WebinarAdmin demo demoCohorts={demoCohorts}/>;
 return null;
}
